# -*- coding: utf-8 -*-
"""Generate src/proxy_auto.cpp: generic forwarders to mcdxdas_orig.dll.

The proxy mcdxdas.dll forwards every MCD API export to the original
Infineon mcdxdas.dll (renamed mcdxdas_orig.dll, loaded from the same
directory) and logs call/return traffic plus selected struct contents.
"""
import re

HDR = r"C:\work\mcd_tas\include\mcd_api.h"
OUT = r"C:\work\mcd_tas\src\proxy_auto.cpp"
EXCLUDE = {"mcd_execute_txlist_f", "mcd_qry_error_info_f",
           "mcd_qry_state_f", "mcd_open_core_f",
           "mcd_qry_reg_map_f", "mcd_qry_trig_set_state_f",
           "mcd_qry_systems_f", "mcd_qry_devices_f", "mcd_qry_cores_f",
           "mcd_qry_rst_classes_f",
           # not exported by the original mcdxdas.dll - keep them absent in
           # the proxy as well so the client sees the same export surface
           "mcd_execute_command_f", "mcd_qry_input_handle_f",
           "mcd_set_global_f"}

text = open(HDR, "r", encoding="utf-8", errors="replace").read()

marker = 'extern "C" MCD_SHARED_LIBRARY_API'
chunks = []
i = 0
while True:
    i = text.find(marker, i)
    if i < 0:
        break
    j = text.find(';', i)
    if j < 0:
        break
    chunks.append(text[i:j + 1])
    i = j + 1

print("prototype chunks:", len(chunks))


def parse(chunk):
    m = re.match(
        r'extern "C" MCD_SHARED_LIBRARY_API\s+(.+?)\s+(mcd_[A-Za-z0-9_]+)\s*\((.*)\)\s*;',
        chunk, re.S)
    if not m:
        return None
    return m.group(1).strip(), m.group(2), m.group(3).strip()


def split_params(params):
    if not params or params == "void":
        return []
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def pname(p):
    m = re.search(r'([A-Za-z_][A-Za-z0-9_]*)\s*(\[[^\]]*\])?\s*$', p)
    return m.group(1) if m else None


lines = ["/* AUTO-GENERATED by tools/gen_proxy.py - generic forwarders */",
         '#include "mcd_api.h"',
         '#include "proxy_common.h"',
         ""]

seen = set()
count = 0
for chunk in chunks:
    pr = parse(chunk)
    if not pr:
        print("UNPARSED:", " ".join(chunk.split())[:140])
        continue
    ret, name, params = pr
    if name in seen:
        print("DUP:", name)
        continue
    seen.add(name)
    if name in EXCLUDE:
        print("SKIP(special):", name)
        continue
    plist = split_params(params)
    names = [pname(x) for x in plist]
    if any(n is None for n in names):
        print("PARAM-NAME-FAIL:", name, plist)
        continue
    sig = ", ".join(plist) if plist else "void"
    args = ", ".join(names)
    tid = "pf_" + name
    lines.append("typedef %s (*%s)(%s);" % (ret, tid, sig))
    lines.append('extern "C" MCD_SHARED_LIBRARY_API %s %s(%s)' % (ret, name, sig))
    lines.append("{")
    lines.append("    static %s pf = 0;" % tid)
    lines.append('    if (!pf) pf = (%s)proxy_orig_proc("%s");' % (tid, name))
    if ret == "void":
        lines.append('    if (!pf) { proxy_log("FATAL: %s missing in orig"); return; }' % name)
    else:
        lines.append('    if (!pf) { proxy_log("FATAL: %s missing in orig"); return MCD_RET_ACT_HANDLE_ERROR; }' % name)
    lines.append('    proxy_log("+ %s");' % name)
    if ret == "void":
        lines.append("    pf(%s);" % args)
        lines.append('    proxy_log("- %s (void)");' % name)
    else:
        lines.append("    %s r = pf(%s);" % (ret, args))
        lines.append('    proxy_log("- %s -> %%d", (int)r);' % name)
        lines.append("    return r;")
    lines.append("}")
    lines.append("")
    count += 1

open(OUT, "w", encoding="utf-8").write("\n".join(lines))
print("wrote %s: %d forwarders, %d lines" % (OUT, count, len(lines)))
